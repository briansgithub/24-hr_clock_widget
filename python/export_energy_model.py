"""Check or explicitly promote the canonical Python/Android energy model export."""
from __future__ import annotations

import argparse
import copy
import json
import math
from pathlib import Path


MODEL_M8 = "M8_adaptive_sleep"
MODEL_M9 = "M9_awake_hybrid"

REQUIRED_PARAMS = (
    "circadian_coefs",
    "reference_sleep_hours",
    "reference_peak_clock",
    "max_phase_shift_hours",
    "tau_wake",
    "tau_sleep",
    "inertia_tau",
    "homeostatic_scale",
    "debt_scale",
    "debt_saturation_hours",
    "inertia_scale",
    "process_s_min",
    "process_s_max",
    "homeostatic_delta_min",
    "homeostatic_delta_max",
)


def validate_model(document: dict, require_promotable_m9: bool = False) -> dict:
    model_id = document.get("model_id")
    if model_id not in (MODEL_M8, MODEL_M9):
        raise ValueError(f"Unsupported model_id: {model_id!r}")
    if model_id == MODEL_M9 and document.get("schema_version") != 2:
        raise ValueError("M9 requires schema_version 2")
    if require_promotable_m9:
        if model_id != MODEL_M9 or not document.get("promotion", {}).get("passed", False):
            raise ValueError("Explicit promotion requires an M9 candidate that passed every gate")

    params = document.get("params")
    if not isinstance(params, dict):
        raise ValueError("Model params must be an object")
    missing = [name for name in REQUIRED_PARAMS if name not in params]
    if missing:
        raise ValueError(f"Missing model params: {', '.join(missing)}")
    harmonics = int(params.get("harmonics", (len(params["circadian_coefs"]) - 1) // 2))
    coefficients = params["circadian_coefs"]
    if harmonics not in (2, 3) or len(coefficients) != 1 + 2 * harmonics:
        raise ValueError("Circadian coefficients do not match a two- or three-harmonic model")
    numeric_values = list(coefficients) + [params[name] for name in REQUIRED_PARAMS[1:]]
    if not all(isinstance(value, (int, float)) and math.isfinite(value) for value in numeric_values):
        raise ValueError("All model parameters must be finite numbers")
    if params["tau_wake"] != 23.0 or params["tau_sleep"] != 4.0:
        raise ValueError("Promotion cannot change fixed Process S time constants")
    if params["reference_sleep_hours"] != 8.0:
        raise ValueError("Promotion cannot change reference sleep")
    if params["debt_saturation_hours"] != 12.0:
        raise ValueError("Promotion cannot change debt saturation")
    if params["max_phase_shift_hours"] != 3.0:
        raise ValueError("Promotion cannot change maximum phase shift")
    validated = copy.deepcopy(document)
    validated.setdefault("schema_version", 1)
    validated["params"]["harmonics"] = harmonics
    return validated


def _kotlin_double(value: float) -> str:
    rendered = format(float(value), ".17g")
    if "e" not in rendered.lower() and "." not in rendered:
        rendered += ".0"
    return rendered


def render_android_constants(document: dict) -> str:
    model = validate_model(document)
    params = model["params"]
    coefficients = ",\n".join(
        f"        {_kotlin_double(value)}" for value in params["circadian_coefs"]
    )
    return f'''// Generated by python/export_energy_model.py. Do not edit by hand.
package com.example.a24_hr_clock.logic

internal object GeneratedEnergyModel {{
    const val SCHEMA_VERSION = {int(model["schema_version"])}
    const val MODEL_ID = "{model["model_id"]}"
    const val HARMONICS = {int(params["harmonics"])}
    val CIRCADIAN_COEFS = doubleArrayOf(
{coefficients}
    )
    const val REFERENCE_SLEEP_HOURS = {_kotlin_double(params["reference_sleep_hours"])}
    const val REFERENCE_PEAK_CLOCK = {_kotlin_double(params["reference_peak_clock"])}
    const val MAX_PHASE_SHIFT_HOURS = {_kotlin_double(params["max_phase_shift_hours"])}
    const val TAU_WAKE = {_kotlin_double(params["tau_wake"])}
    const val TAU_SLEEP = {_kotlin_double(params["tau_sleep"])}
    const val INERTIA_TAU = {_kotlin_double(params["inertia_tau"])}
    const val HOMEOSTATIC_SCALE = {_kotlin_double(params["homeostatic_scale"])}
    const val DEBT_SCALE = {_kotlin_double(params["debt_scale"])}
    const val DEBT_SATURATION_HOURS = {_kotlin_double(params["debt_saturation_hours"])}
    const val INERTIA_SCALE = {_kotlin_double(params["inertia_scale"])}
    const val PROCESS_S_MIN = {_kotlin_double(params["process_s_min"])}
    const val PROCESS_S_MAX = {_kotlin_double(params["process_s_max"])}
    const val HOMEOSTATIC_DELTA_MIN = {_kotlin_double(params["homeostatic_delta_min"])}
    const val HOMEOSTATIC_DELTA_MAX = {_kotlin_double(params["homeostatic_delta_max"])}
}}
'''


def check_export(source: Path, android_output: Path) -> None:
    document = json.loads(source.read_text(encoding="utf-8"))
    expected = render_android_constants(document)
    actual = android_output.read_text(encoding="utf-8") if android_output.exists() else ""
    if actual != expected:
        raise RuntimeError(
            "Python/Android energy model drift detected. "
            "Regenerate only through the explicit exporter."
        )


def promote_candidate(candidate_path: Path, production_path: Path, android_output: Path) -> None:
    candidate = validate_model(
        json.loads(candidate_path.read_text(encoding="utf-8")),
        require_promotable_m9=True,
    )
    production = {
        "schema_version": candidate["schema_version"],
        "model_id": candidate["model_id"],
        "params": candidate["params"],
        "training": candidate.get("training", {}),
        "promotion": candidate["promotion"],
    }
    production_path.write_text(json.dumps(production, indent=2) + "\n", encoding="utf-8")
    android_output.write_text(render_android_constants(production), encoding="utf-8")


def main() -> None:
    repo_root = Path(__file__).resolve().parents[1]
    production_path = repo_root / "python" / "personal_energy_fit.json"
    android_output = (
        repo_root / "android" / "app" / "src" / "main" / "java" /
        "com" / "example" / "a24_hr_clock" / "logic" / "GeneratedEnergyModel.kt"
    )
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--check", action="store_true")
    action.add_argument("--promote", type=Path, metavar="CANDIDATE_JSON")
    parser.add_argument("--source", type=Path, default=production_path)
    parser.add_argument("--android-output", type=Path, default=android_output)
    args = parser.parse_args()

    if args.check:
        check_export(args.source, args.android_output)
        print("Python/Android energy model constants are synchronized.")
    else:
        promote_candidate(args.promote, production_path, args.android_output)
        print(f"Promoted {args.promote} and regenerated Android constants.")


if __name__ == "__main__":
    main()
